/* ============================================================================
   17_BlueTrack_ReportExport.sql

   RUN THIS AFTER 01-16. Guarded -- safe to re-run.

   D-220: every report under Reports can be exported as CSV or Excel
   (.xlsx), generated by the API, decided by the user on 2026-10-13.

     web.app_config.ExportMaxRows   the most rows one export may hold
                                    (default 100000, 1 to 1000000; an .xlsx
                                    sheet holds 1048576 rows). When more rows
                                    match, the export is refused with the
                                    count, never cut short silently. Edited on
                                    Global Application Configuration.
     ReportExport audit event type  every export is audit-logged: who, which
                                    report, the format, the filter and sort
                                    parameters, and the row count.
   ============================================================================ */

USE $DatabaseName$;
GO

IF COL_LENGTH('web.app_config', 'ExportMaxRows') IS NULL
    ALTER TABLE web.app_config ADD ExportMaxRows INT NOT NULL
        CONSTRAINT DF_app_config_ExportMaxRows DEFAULT 100000
        CONSTRAINT CK_app_config_ExportMaxRows CHECK (ExportMaxRows BETWEEN 1 AND 1000000);
GO

INSERT INTO web.dim_audit_event_type (EventTypeName, Description)
SELECT 'ReportExport', 'A report was exported as CSV or Excel (the report, format, filters and sort, and row count)'
WHERE NOT EXISTS (SELECT 1 FROM web.dim_audit_event_type WHERE EventTypeName = 'ReportExport');
GO
